UPDATE "Account"
SET "category" = CASE
  WHEN "code" = 'SYS-PROPERTY-INVENTORY' THEN 'PURCHASE'
  WHEN "code" IN ('SYS-SELLER-PAYABLES', 'SYS-ACQUISITION-ACCRUALS') THEN 'SUPPLIER'
  WHEN "code" = '2000' AND "name" = 'Customer advances' THEN 'CUSTOMER'
  ELSE "category"
END
WHERE "code" IN (
  'SYS-PROPERTY-INVENTORY',
  'SYS-SELLER-PAYABLES',
  'SYS-ACQUISITION-ACCRUALS',
  '2000'
);
